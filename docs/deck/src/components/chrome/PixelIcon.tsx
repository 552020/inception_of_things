export function PixelIcon({ name, size = 32 }: { name: GlyphName | "error" | "info" | "warning"; size?: number }) {
  const rows = PIXEL_ICONS[name] ?? [];
  const rects: { x: number; y: number; w: number; c: string }[] = [];
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      const ch = row[x];
      let w = 1;
      while (x + w < row.length && row[x + w] === ch) w++;
      if (ch !== "." && PIXEL_PALETTE[ch]) rects.push({ x, y, w, c: PIXEL_PALETTE[ch] });
      x += w;
    }
  });
  return (
    <svg className="pixel-icon" viewBox="0 0 32 32" width={size} height={size} shapeRendering="crispEdges" aria-hidden="true">
      {rects.map((r, i) => (
        <rect key={i} x={r.x} y={r.y} width={r.w} height="1" fill={r.c} />
      ))}
    </svg>
  );
}
